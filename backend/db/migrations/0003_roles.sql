-- Roles (Admin -> Roles, services/roles.js): every user has one role, and the
-- role decides which pages they can open. The role's pages are also written onto
-- its members (app.users.is_admin / permissions / tab_permissions), which is what
-- sign-in and page checks read. The built-in Administrator role is the only one
-- with is_system and is_admin.

CREATE TABLE app.roles (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text        NOT NULL,
  description      text        NOT NULL DEFAULT '',
  is_admin         boolean     NOT NULL DEFAULT false,
  is_system        boolean     NOT NULL DEFAULT false,
  permissions      jsonb       NOT NULL DEFAULT '[]'::jsonb,
  tab_permissions  jsonb       NOT NULL DEFAULT '[]'::jsonb,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       text        NOT NULL DEFAULT '',
  CONSTRAINT roles_name_length CHECK (char_length(name) BETWEEN 1 AND 60),
  CONSTRAINT roles_permissions_is_array CHECK (jsonb_typeof(permissions) = 'array'),
  CONSTRAINT roles_tab_permissions_is_array CHECK (jsonb_typeof(tab_permissions) = 'array')
);
CREATE UNIQUE INDEX roles_name_uk ON app.roles (lower(name));
CREATE UNIQUE INDEX roles_single_system_role ON app.roles (is_system) WHERE is_system;

-- A role that still has members cannot be deleted (default ON DELETE RESTRICT).
ALTER TABLE app.users ADD COLUMN role_id bigint REFERENCES app.roles (id);
CREATE INDEX users_role_idx ON app.users (role_id);

COMMENT ON TABLE app.roles IS 'Admin -> Roles: page access per role; members get the role''s pages.';
COMMENT ON COLUMN app.users.role_id IS 'The user''s one role (NULL while pending without a role).';

GRANT SELECT, INSERT, UPDATE, DELETE ON app.roles TO astar_erp_app;
GRANT USAGE, SELECT ON SEQUENCE app.roles_id_seq TO astar_erp_app;
GRANT SELECT ON app.roles TO astar_erp_read;

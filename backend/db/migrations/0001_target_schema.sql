-- Creates the monthly partition that contains `month` for every partitioned audit table.
-- Called by the backend at start-up and daily (current + next month); retention drops
-- partitions older than USER_ACTIVITY_RETENTION_DAYS.
CREATE OR REPLACE FUNCTION audit.ensure_month_partitions(month date)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  parent text;
  from_ts timestamptz := date_trunc('month', month::timestamptz);
  to_ts   timestamptz := date_trunc('month', month::timestamptz) + interval '1 month';
BEGIN
  FOREACH parent IN ARRAY ARRAY['failed_login_attempts', 'authentication_events', 'page_visit_events',
                                'user_action_events', 'session_cookie_events'] LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS audit.%I PARTITION OF audit.%I FOR VALUES FROM (%L) TO (%L)',
      parent || '_' || to_char(from_ts, 'YYYYMM'), parent, from_ts, to_ts);
  END LOOP;
END $$;

SELECT audit.ensure_month_partitions(current_date);
SELECT audit.ensure_month_partitions((current_date + interval '1 month')::date);

-- Safety net: if the partition job stops, events land here instead of failing the
-- request. Alert when a default partition is not empty, then move its rows out
-- before creating the matching month partition.
CREATE TABLE audit.failed_login_attempts_default PARTITION OF audit.failed_login_attempts DEFAULT;
CREATE TABLE audit.authentication_events_default PARTITION OF audit.authentication_events DEFAULT;
CREATE TABLE audit.page_visit_events_default     PARTITION OF audit.page_visit_events     DEFAULT;
CREATE TABLE audit.user_action_events_default    PARTITION OF audit.user_action_events    DEFAULT;
CREATE TABLE audit.session_cookie_events_default PARTITION OF audit.session_cookie_events DEFAULT;

-- ---------------------------------------------------------------------------
-- mirror  (Google Sheets copies; rebuilt by the sync job, read by the API)
-- Each source range becomes one table named <db>_<table>, e.g. mirror.db6_vessel_db.
-- Columns are created from the sheet header row: _sheet_row integer plus one text
-- column per header (snake_case, de-duplicated). Rebuild = load mirror.<t>__staging,
-- then in one short transaction: DROP old, RENAME staging, upsert database_meta.
-- ---------------------------------------------------------------------------

CREATE TABLE mirror.database_meta (
  database_name          text        NOT NULL,   -- DB1..DB17
  table_name             text        NOT NULL,
  layout                 text        NOT NULL CHECK (layout IN ('separate', 'side-by-side', 'raw-grid')),
  source_sheet_id        text        NOT NULL,
  service_account_email  text        NOT NULL,
  source_tab             text        NOT NULL,
  source_range           text        NOT NULL,
  row_count              integer     NOT NULL,
  column_count           integer     NOT NULL,
  source_hash            text        NOT NULL,
  version                bigint      NOT NULL DEFAULT 1,  -- bumped on every rebuild; replaces the SQLite file-signature cache key
  pulled_at              timestamptz NOT NULL,
  PRIMARY KEY (database_name, table_name)
);

CREATE TABLE mirror.column_map (
  database_name  text    NOT NULL,
  table_name     text    NOT NULL,
  ordinal        integer NOT NULL,
  column_name    text    NOT NULL,
  source_label   text    NOT NULL,
  PRIMARY KEY (database_name, table_name, ordinal),
  FOREIGN KEY (database_name, table_name) REFERENCES mirror.database_meta (database_name, table_name)
    ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);


-- Admin -> Sheets Config: connection settings for the six synced spreadsheets
-- (services/spreadsheetSources.js). Tabs and ranges stay in config/dataSources.js;
-- this table holds which spreadsheet, which service account, and whether it is
-- synced. Replaces the legacy app.sheets_config list, which the sync never read.

CREATE TABLE app.spreadsheet_sources (
  key                    text PRIMARY KEY
    CHECK (key IN ('AASTAR_SALES', 'GR', 'VESSEL', 'STOCK', 'SHIPMENT_DETAILS', 'TPG_OPERATIONS')),
  sheet_id               text        NOT NULL DEFAULT '',
  service_account_email  text        NOT NULL DEFAULT '',
  enabled                boolean     NOT NULL DEFAULT true,
  updated_at             timestamptz NOT NULL DEFAULT now(),
  updated_by             text        NOT NULL DEFAULT ''
);

CREATE TABLE app.spreadsheet_source_changes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key         text        NOT NULL REFERENCES app.spreadsheet_sources (key),
  field       text        NOT NULL CHECK (field IN ('sheet_id', 'service_account_email', 'enabled')),
  old_value   text,
  new_value   text,
  changed_by  text        NOT NULL,
  changed_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX spreadsheet_source_changes_key_idx
  ON app.spreadsheet_source_changes (key, changed_at DESC);

COMMENT ON TABLE app.sheets_config IS 'Legacy: superseded by app.spreadsheet_sources; not read by the bulk sync.';

GRANT SELECT, INSERT, UPDATE ON app.spreadsheet_sources TO astar_erp_app;
GRANT SELECT, INSERT ON app.spreadsheet_source_changes TO astar_erp_app;
GRANT USAGE, SELECT ON SEQUENCE app.spreadsheet_source_changes_id_seq TO astar_erp_app;
GRANT SELECT ON app.spreadsheet_sources, app.spreadsheet_source_changes TO astar_erp_read;
